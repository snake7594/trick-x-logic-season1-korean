"""조각 경계에 빠진 띄어쓰기를 채운다.

번역이 조각별로 이뤄져 경계의 공백이 빠졌다(6,089곳). 뒤 조각이 조사·어미로
시작하면 붙이고, 아니면 띄운다. 애매하면 **띄우는 쪽**을 고른다 —
'특히뛰어난'처럼 붙는 쪽이 훨씬 나쁘기 때문이다.
"""
H = lambda c: '가' <= c <= '힣'

# 앞말에 붙는 조사·어미 (이걸로 시작하면 공백을 넣지 않는다)
ATTACH = (
    '에게', '에서', '에겐', '으로', '라는', '라고', '라며', '라서', '라도',
    '이라', '부터', '까지', '처럼', '보다', '밖에', '마다', '조차', '한테',
    '께서', '이나', '이란', '이며', '이자', '인데', '였다', '이었', '입니',
    '이야', '이지', '하고', '하는', '하지', '하며', '하여', '하기', '한다',
    '했다', '해서', '해도', '해야', '되는', '되어', '되지', '스럽', '답게',
    '같은', '같이', '이란', '이든', '이라도', '으로서', '으로써',
)
ATTACH_EXC = ('하지만', '하기는 하지만')      # 접속부사는 띄운다
JOSA1 = set('이가은는을를의에와과도만로랑께')
# 종결어미로 끝났으면 뒤의 '이/가/은/는…'은 조사가 아니라 관형사·새 낱말이다
FINAL = set('다요까죠네지야어아라오소군세게나냐노마자')


def need_space(prev, nxt):
    """경계에 공백이 필요한가."""
    if not prev or not nxt:
        return False
    a, b = prev[-1], nxt[0]
    if not (H(a) and H(b)):
        return False
    if nxt.startswith(ATTACH_EXC):
        return True
    if nxt.startswith(ATTACH):
        return False
    if b in JOSA1 and (len(nxt) == 1 or not H(nxt[1])):
        return a in FINAL          # '…입니다' + '이 사실' 은 띄운다
    return True
