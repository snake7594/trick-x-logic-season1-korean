# -*- coding: utf-8 -*-
"""조각 경계에 빠진 띄어쓰기를 채운다.

번역이 조각별로 이뤄져 경계의 공백이 빠졌다(6,089곳). 뒤 조각이 조사·어미로
시작하면 붙이고, 아니면 띄운다. 애매하면 **띄우는 쪽**을 고른다 —
'특히뛰어난'처럼 붙는 쪽이 훨씬 나쁘기 때문이다.
"""
H = lambda c: '가' <= c <= '힣'

# 앞말에 붙는 조사·어미 (이걸로 시작하면 공백을 넣지 않는다)
ATTACH = (
    '에게', '에서', '에겐', '으로', '라는', '라고', '라며', '라서', '라도',
    '이라', '부터', '까지', '처럼', '보다', '밖에', '마다', '조차', '한테',
    '께서', '이나', '이란', '이며', '이자', '인데', '였다', '이었', '입니',
    '이야', '이지', '하고', '하는', '하지', '하며', '하여', '하기', '한다',
    '했다', '해서', '해도', '해야', '되는', '되어', '되지', '스럽', '답게',
    '같은', '같이', '이란', '이든', '이라도', '으로서', '으로써',
    '이다', '이고', '이며', '이지만', '입니다', '이었다', '이라면',
)
ATTACH_EXC = ('하지만', '하기는 하지만')      # 접속부사는 띄운다
JOSA1 = set('이가은는을를의에와과도만로랑께')
# 종결어미로 끝났으면 뒤의 '이/가/은/는…'은 조사가 아니라 관형사·새 낱말이다
FINAL = set('다요까죠네지야어아라오소군세게나냐노마자')


# 뒤 조각의 **일본어**가 이걸로 시작하면 앞말에 붙는 자리다. 한국어만 보면
# '추리 파일'+'을 열어'(조사)와 '그 책은'+'이 명계에서'(관형사)를 못 가른다.
# 원문은 조사가 글자로 드러나 있어 확실하다.
JP_HEAD = (
    'を', 'が', 'は', 'に', 'へ', 'で', 'と', 'も', 'の', 'や', 'ば', 'ぞ',
    'ね', 'よ', 'か', 'な', 'ん', 'だ', 'です', 'ます', 'から', 'まで',
    'より', 'ので', 'のに', 'けど', 'けれ', 'という', 'って', 'たら', 'たり',
    'ても', 'でも', 'しか', 'こそ', 'さえ', 'だけ', 'ほど', 'くらい',
    'ぐらい', 'など', 'なんて', 'ながら', 'つつ', 'した', 'して', 'する',
    'され', 'い', 'く', 'り', 'れ', 'め', 'ら', 'せ', 'え', 'け',
)
# 닫는 따옴표는 문장 끝이 아니다 — 『アカシャ』+'は…' 처럼 조사가 붙는다
JA_BREAK = ('、', '。', '！', '？', '，', '．')


def need_space(prev, nxt, ja_prev=None, ja_next=None):
    """경계에 공백이 필요한가. 원문을 주면 조사 판정을 원문으로 한다."""
    if not prev or not nxt:
        return False
    if nxt[0] in '.,!?…」』）)、。，':
        return False               # 뒤가 문장부호로 시작하면 붙인다
    if nxt.startswith(ATTACH_EXC):
        return True
    if nxt.startswith(ATTACH):
        return False
    # ① 원문이 끊겼으면 뒤는 새 낱말이다. '그 책은'+'이 명계에서' 처럼
    #    한국어만 봐서는 조사인지 관형사인지 못 가르는 자리를 여기서 가른다.
    if ja_prev is not None and ja_prev.rstrip().endswith(JA_BREAK):
        return True
    # ② 원문이 조사·어미로 이어지면 붙인다. '추리 파일'+'을 열어'.
    if ja_next is not None and ja_next.startswith(JP_HEAD):
        return False
    a, b = prev[-1], nxt[0]
    # 여는 따옴표 앞은 띄운다 — '명계에서「아카샤」' 처럼 붙어 나온다.
    # 일본어는 안 띄우지만 한국어는 띄우는 게 맞다.
    if H(a) and b in '「『〈《‘“(（':
        return True
    if not (H(a) and H(b)):
        return False
    # ③ 원문이 안 끊겼는데 뒤가 홑음절 조사로 시작하면 붙인다.
    #    '융단'+'도 조명도', '경련'+'을 일으키더니'.
    if b in JOSA1 and (len(nxt) == 1 or not H(nxt[1])):
        return a in FINAL          # '…입니다' + '이 사실' 은 띄운다
    return True
